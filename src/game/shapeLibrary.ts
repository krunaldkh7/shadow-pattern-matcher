const DIGIT_SHAPES = Object.entries(DIGITS).map(([d, strokes]) => shape(`digit-${d}`, `Number ${d}`, ...strokes));

/**
 * Interleave the families so consecutive levels feel different: two objects,
 * then one geometric shape, then a letter or numeral, repeated.
 */
export function buildExtendedShapes(): ShapeDef[] {
  const queues = [OBJECTS.slice(), GEOMETRY.slice(), [...LETTER_SHAPES, ...DIGIT_SHAPES]];
  const pattern = [0, 1, 0, 2];
  const out: ShapeDef[] = [];
  let p = 0;
  while (queues.some((q) => q.length)) {
    const q = queues[pattern[p++ % pattern.length]];
    const next = q.shift() ?? queues.find((x) => x.length)?.shift();
    if (next) out.push(next);
  }
  return out;
}
