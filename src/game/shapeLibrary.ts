import type { Point2, ShapeDef, Stroke } from './shapes';

/**
 * The extended shape catalogue: geometric families built from formulas plus
 * hand-authored objects, letters and numerals. Same conventions as shapes.ts:
 * polylines in a ~[-1, 1] box, +Y up.
 */

const closed = (points: Point2[]): Stroke => ({ points, closed: true });
const open = (points: Point2[]): Stroke => ({ points, closed: false });
const shape = (id: string, name: string, ...strokes: Stroke[]): ShapeDef => ({ id, name, strokes });

/** Closed curve sampled from a polar radius function r(angle). */
function polar(r: (a: number) => number, n = 64, cx = 0, cy = 0, sx = 1, sy = 1): Stroke {
  const pts: Point2[] = [];
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    const k = r(a);
    pts.push([cx + Math.cos(a) * k * sx, cy + Math.sin(a) * k * sy]);
  }
  return closed(pts);
}

/** Arc from angle a0 to a1 (radians), as an open polyline. */
function arcPts(cx: number, cy: number, rx: number, ry: number, a0: number, a1: number, n = 16): Point2[] {
  const pts: Point2[] = [];
  for (let i = 0; i <= n; i++) {
    const a = a0 + ((a1 - a0) * i) / n;
    pts.push([cx + Math.cos(a) * rx, cy + Math.sin(a) * ry]);
  }
  return pts;
}

const ellipse = (cx: number, cy: number, rx: number, ry: number, n = 24) => polar(() => 1, n, cx, cy, rx, ry);

function polygon(sides: number, rot = Math.PI / 2, r = 0.95): Stroke {
  const pts: Point2[] = [];
  for (let i = 0; i < sides; i++) {
    const a = rot + (i / sides) * Math.PI * 2;
    pts.push([Math.cos(a) * r, Math.sin(a) * r]);
  }
  return closed(pts);
}

function star(spikes: number, inner: number): Stroke {
  const pts: Point2[] = [];
  for (let i = 0; i < spikes * 2; i++) {
    const r = i % 2 === 0 ? 0.98 : inner;
    const a = Math.PI / 2 + (i * Math.PI) / spikes;
    pts.push([Math.cos(a) * r, Math.sin(a) * r]);
  }
  return closed(pts);
}

function gear(teeth: number): Stroke[] {
  const pts: Point2[] = [];
  const per = 4;
  for (let i = 0; i < teeth * per; i++) {
    const phase = i % per;
    const r = phase === 0 || phase === 1 ? 0.95 : 0.72;
    const a = ((i + 0.5) / (teeth * per)) * Math.PI * 2;
    pts.push([Math.cos(a) * r, Math.sin(a) * r]);
  }
  return [closed(pts), ellipse(0, 0, 0.28, 0.28, 14)];
}

